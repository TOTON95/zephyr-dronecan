"""Generate Kconfig.messages and src/dronecan_msg_table.c from the DSDL definitions.

Usage: scripts/gen_kconfig_messages.py [--check] <DSDL dir>

Run it after the DSDL revision changes and commit the result. With --check nothing is written: it
fails when the committed files differ from what the DSDL gives. Needs the 'dronecan' Python package
(requirements.txt).
"""

import argparse
import difflib
import os
import sys

import dronecan.dsdl

NAMESPACES = ("uavcan", "dronecan", "ardupilot")

# Always built, no prompt: the core sends and decodes it
REQUIRED = {"uavcan.protocol.NodeStatus"}

# Selected by default
DEFAULT_ON = {"uavcan.protocol.debug.LogMessage"}

HEADER = "Generated by scripts/gen_kconfig_messages.py -- do not edit."


def symbol(full_name):
    return "DRONECAN_MSG_" + full_name.replace(".", "_").upper()


def load(dsdl_dir):
    # One call: the namespaces refer to each other
    types = dronecan.dsdl.parse_namespaces([os.path.join(dsdl_dir, ns) for ns in NAMESPACES])
    # Broadcast messages that have a data type ID. The rest are nested types or services.
    msgs = [t for t in types if t.kind == t.KIND_MESSAGE and t.default_dtid is not None]
    return sorted(msgs, key=lambda t: t.full_name)


def render_kconfig(msgs):
    out = [
        "# " + HEADER,
        "",
        'menu "Messages"',
        "",
    ]
    for t in msgs:
        ns = t.full_name.split(".")[0]
        if t.full_name in REQUIRED:
            out.append(f"config {symbol(t.full_name)}")
            out.append("\tdef_bool y")
        else:
            out.append(f"config {symbol(t.full_name)}")
            out.append(f'\tbool "{t.full_name}"')
            if t.full_name in DEFAULT_ON:
                out.append("\tdefault y")
            if ns != "uavcan":
                out.append(f"\tdepends on DRONECAN_DSDL_{ns.upper()}")
        out.append("\thelp")
        out.append(f"\t  Data type ID {t.default_dtid}.")
        out.append("")
    out.append("endmenu # Messages")
    return "\n".join(out) + "\n"


def render_table(msgs):
    # Same values as in the dronecan_dsdlc headers
    out = [
        "/* " + HEADER + " */",
        "",
        "#include <zephyr/sys/util.h>",
        "",
        '#include "dronecan_msg_table.h"',
        "",
        "const struct dronecan_msg_entry dronecan_msg_table[] = {",
    ]
    for t in msgs:
        max_size = (t.get_max_bitlen() + 7) // 8
        out.append(f"#ifdef CONFIG_{symbol(t.full_name)}")
        out.append(
            f'\t{{"{t.full_name}", {{{t.default_dtid}, 0x{t.get_data_type_signature():X}ULL, {max_size}}}}},'
        )
        out.append("#endif")
    out += [
        "};",
        "",
        "const size_t dronecan_msg_table_len = ARRAY_SIZE(dronecan_msg_table);",
    ]
    return "\n".join(out) + "\n"


def check(files, root, dsdl_dir):
    stale = []
    for rel, text in files.items():
        path = os.path.join(root, rel)
        current = open(path).read() if os.path.exists(path) else ""
        if current == text:
            continue
        stale.append(rel)
        diff = list(difflib.unified_diff(current.splitlines(True), text.splitlines(True),
                                         f"{rel} (committed)", f"{rel} (from the DSDL)", n=0))
        sys.stdout.writelines(diff[:40])
        if len(diff) > 40:
            print(f"... {len(diff) - 40} more lines")
    if stale:
        sys.exit(f"{', '.join(stale)} out of date: run scripts/gen_kconfig_messages.py {dsdl_dir} "
                 "and commit the result")


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("dsdl_dir", help="DSDL repository (contains uavcan/, dronecan/, ardupilot/)")
    ap.add_argument("--check", action="store_true",
                    help="write nothing, fail if the committed files are out of date")
    args = ap.parse_args()

    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    msgs = load(args.dsdl_dir)
    missing = REQUIRED - {t.full_name for t in msgs}
    if missing:
        sys.exit(f"required messages not found in {args.dsdl_dir}: {sorted(missing)}")
    files = {
        "Kconfig.messages": render_kconfig(msgs),
        os.path.join("src", "dronecan_msg_table.c"): render_table(msgs),
    }
    if args.check:
        check(files, root, args.dsdl_dir)
        print(f"{len(msgs)} messages, the committed files are up to date")
        return
    for rel, text in files.items():
        with open(os.path.join(root, rel), "w") as f:
            f.write(text)
    print(f"{len(msgs)} messages")


if __name__ == "__main__":
    main()
